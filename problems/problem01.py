'''
문제 01 (problem01.py)
------------------------------------------------------------------------
반의 성적표를 정리하고 있습니다.
성적표가 2차원 리스트 scores로 주어질 때
(한 줄이 한 학생이고, 그 줄 안의 값들이 그 학생의 과목별 점수),
각 학생의 총점을 순서대로 모아 리스트로 반환하는
get_student_totals 함수를 완성하시오.

- 학생 수와 과목 수는 서로 다를 수 있습니다.
- 모든 학생은 같은 개수의 과목 점수를 가집니다.
- 학생은 최소 1명, 과목은 최소 1개 있습니다.
- 결과 리스트의 길이는 학생 수와 같아야 합니다.

예시_01)
    입력: [[80, 90, 70], [60, 100, 85]]
    출력: [240, 245]        (학생 2명, 과목 3개)

예시_02)
    입력: [[50]]
    출력: [50]

예시_03)
    입력: [[1, 2], [3, 4], [5, 6]]
    출력: [3, 7, 11]        (학생 3명, 과목 2개)

제한 기능: sum
           => 사용해도 됩니다. 다만 기본적으로 사용하지 말고 구현해보세요.
'''

# ============================================================
# [1] 신호어 찾기  (코드를 치기 전에 작성)
# ============================================================
# 지문에서 찾은 신호어 : "각 학생의 총점을 순서대로 모아"
# 선택한 골격         : 누적
# 그렇게 판단한 이유   : 학생 점수를 모은 리스트 내 원소들을 모두 더해 리스트로 
#                     반환해야 하니 누적을 사용한다.
# 반환 형태 (지문에서 그대로 옮겨 적기) : "리스트로 반환하는"
#
# 추가 질문 1: 반복문이 몇 겹 필요한가요? 그렇게 판단한 근거는?
# 답 : 두 겹. 학생의 점수값에 접근해야 하고, 그렇게 하려면 리스트를 두 번 벗겨야 한다. 
#
# 추가 질문 2: 예시_03에서 학생은 3명, 과목은 2개입니다.
#             결과 리스트의 길이는 3인가요, 2인가요? 왜 그런가요?
# 답 : 3이다. 학생마다의 점수 총합을 리스트의 원소로 하니 학생의 수가 곧
#            총점의 수다. 학생의 수는 셋이다.

# ============================================================
# [2] 변수 역할표  (코드를 치기 전에 작성)
# ------------------------------------------------------------
# 만들 변수마다 아래 다섯 칸을 채우세요.
# ★ 마지막 칸이 이 문제의 핵심입니다.
#    변수마다 "이 값은 언제 처음 상태로 돌아가야 하는가"를 먼저 생각하세요.
# ============================================================
# 변수 이름 | 담기는 것 | 시작값 | 시작값의 이유 | 어느 반복문 안/밖에서 만드는가
# stu_total|한 학생의 점수 총합|  0 |점수를 순회하며 더해야 한다|바깥 for문 안/ 안쪽 for문 밖 
# stu_total_lst|학생들의 점수 총합| [] |학생 점수 총합을 추가해야 한다|안쪽 for문 뒤/ 바깥 for문 밖
#          |          |       |              |


# ============================================================
# [3] 설계 - 무엇을 / 왜
# ------------------------------------------------------------
# ★ 이 문제의 핵심 질문입니다. 반드시 [왜]에 답하세요.
#
#   한 학생의 총점을 담는 변수를 '바깥 for 문보다 위'에서 0으로 만들면
#   어떻게 되나요? [[80, 90, 70], [60, 100, 85]] 를 넣어 보고,
#   나오는 결과와 그 이유를 본인 말로 설명하세요.
# ============================================================
# 0. [한 학생의 총점 변수 - 시작값과 만드는 위치]
#     stu_total = 0/ 안쪽 for문 밖, 바깥 for문 안
#    [왜]
#     [[80, 90, 70], [60, 100, 85]]를 넣으면 [240, 485]가 나온다.
#     한 학생의 총점 변수가 바깥 for문보다 위에 있으면 첫 학생까지는 정상적으로
#     총점이 나오고 리스트에 추가된다. 바깥 for문이 다음 학생 리스트를 꺼낼 때 
#     초기화되지 않아 240인 상태서 안쪽 for문이 꺼내 더하는 점수가 누적된다.
#     그 결과 60, 100, 85가 더해져 485라는 값이 나와 점수 총합 리스트에 추가된다. 
# 1. [바깥 반복문은 무엇을 하나씩 꺼내는가]
#     scores리스트에서 한 학생의 과목별 점수 모음 리스트를 꺼낸다.
#    [왜]
#     중첩 반복문에서 우선적으로 접근하는 값은 상대적으로 바깥에 있는 리스트다. 
#     학생의 점수 총합을 구하기 위해 먼저 그 점수들을 모은 리스트에 접근한다.
# 2. [안쪽 반복문은 무엇을 하나씩 꺼내는가]
#     score리스트에서 한 학생의 과목별 점수를 꺼낸다.
#    [왜]
#     안쪽 리스트에 접근했으니 그 안의 값을 꺼내 누적시켜야 안쪽 반복문을 돌리며
#     결과 리스트에 추가할 값을 구할 수 있다.  
# 3. [결과 리스트에 값을 추가하는 자리는 어디인가]
#    (안쪽 for 안 / **안쪽 for 뒤, 바깥 for 안** / 바깥 for 뒤)
#    [왜]
#     우선 안쪽 for문을 다 돌아야 결과 리스트에 넣을 값이 나오니 안쪽 for문 앞에서는
#     결과 리스트에 값을 추가할 수 없다. 바깥 for문 밖에 두면 안쪽 for문을 한 번 돌 때가
#     아닌 다 돌고 난 뒤의 값을 한 번만 추가하고 반복문이 마무리된다.

def get_student_totals(scores):
    stu_total_lst = []
    for score in scores:
        stu_total = 0
        for subject in score:
            stu_total += subject
        stu_total_lst.append(stu_total)
    return stu_total_lst

