# ------------------------------------------------------------
# ★ 이 문제의 핵심 질문 두 개입니다. 반드시 [왜]에 답하세요.
#
#   (1) len(scores) 와 len(scores[0]) 은 각각 무엇의 개수인가요?
#       예시_03([[1, 2], [3, 4], [5, 6]])으로 두 값을 직접 출력해 보세요.
#       그리고 반복 범위에 둘을 바꿔 넣으면 각각 어떻게 되는지
#       예시_01과 예시_03으로 확인하고 결과를 적으세요.
#
#   (2) scores[r][c] 를 실수로 scores[c][r] 이라고 쓰면 어떻게 되나요?
#       예시_03([[1, 2], [3, 4], [5, 6]])과
#       예시_04([[1, 2], [3, 4]])를 각각 넣어 보세요.
#       두 입력의 결과가 서로 다른 방식으로 잘못됩니다. 무엇이 다른가요?
# ============================================================
# 0-1. [반복문 두 개의 범위를 각각 무엇으로 둘 것인가]
#       len(scores), len(scores[0])
#      [왜]
#       len(scores)는 각 '학생'의 리스트 길이다. len(scores[0])는 한 학생이 가진 
#       '각 과목 점수'의 리스트 길이다. 학생마다 다른 과목 혹은 응시 과목수가 다른 경우
#       len(scores[0])이 '각 과목 점수'의 리스트를 대표할 수 없으나 해당 문제 조건은 
#       이를 가능케 한다. 예시_03의 경우 각각 3, 2가 나온다. 학생 수 3명, 과목 수 2개.
#       반복 범위에 둘을 바꿔 넣으면 예시_01의 경우 3, 2 예시_03의 경우 2, 3이 나온다.
#       
#        
# 0-2. [한 과목의 총점 변수 - 시작값과 만드는 위치]
#       sub_total = 0을 안쪽 반복문 밖, 바깥 반복문 안에 둔다.
#      [왜]
#       한 과목의 총점을 학생 수 리스트를 순회하며 더해가야 하기에 안쪽 반복문이
#       돌 때마다 초기화되지 않도록 바깥에 둔다. 바깥 반복문이 돌 때마다 모든 과목의
#       총점을 모은 리스트에 추가하고 다른 과목으로 넘어가기 전 초기화해야 하니 바깥 반복문의 안쪽.
# 1. [무엇을]
#     range(len(score[0]))에서 각 과목을 하나씩 꺼낸 후, range(len(scores))에서 
#     각 학생을 꺼내며 과목 대응값을 더한다. 
#    [왜]
#     문제의 요구조건은 각 과목의 총합을 모아 반환하는 것이다. 내부 리스트의 총합이 아닌
#     내부 리스트에서 특정 인덱스를 공유하는 과목 점수에 접근해야 한다. 과목의 인덱스를
#     순회하며 이전 문제와 다르게 과목의 인덱스에 대응되는 값만을 더한다.
# 2. [scores[r][c] 에서 앞의 대괄호는 무엇을 고르고, 뒤의 대괄호는 무엇을 고르는가]
#     앞의 대괄호는 '어떤 학생'인지 고른다. 뒤의 대괄호는 '어떤 과목'인지 고른다.
#    [왜]
#     중첩 리스트는 늘 바깥으로부터 안쪽의 값에 접근한다. 다루려는 값의 조건이 달라
#     지긴 했으나 고정된 접근 순서에 맞춰 지정해야 한다. 
#     
#     scores[c][r]로 변경 후 예시_03을 넣었을 때
#     scores[c][r]의 r부분에서 IndexError가 발생. scores[0][2]에서 
#     리스트 범위를 초과해 오류가 났다.
#     예시_04를 넣었을 때 [3, 7]을 반환했다. 우연히 과목 인덱스와 학생 수가 2개로 동일하다.
#     접근 자체는 가능해 IndexError는 발생하지 않았으나 접근 과정 상 반복 변수가 
#     뒤바뀌어 의도하지 않은 값(과목 인덱스가 학생 인덱스처럼 취급됨)이 총합에 
#     합산, 학생당 점수 총합의 형태로 반환되었다.
#     
# 3. [결과 리스트에 값을 추가하는 자리는 어디인가]
#     안쪽 for문 뒤, 바깥 for문 안쪽
#    [왜]
#     결과 리스트에 안쪽 for문을 다 돌아 합산된 값을 추가해야 하기에 안쪽 for문 뒤
#     에 위치시킨다. 바깥 for문 바깥에 두면 마지막 값만 합산되고 함수가 종료되니 안 된다.

def get_subject_totals(scores):
    sub_totals = []
    for c in range(len(scores[0])):
        sub_total = 0
        for r in range(len(scores)):
            sub_total += scores[r][c]
        sub_totals.append(sub_total)
    # print(len(scores[0]))
    # print(len(scores))
    return sub_totals

