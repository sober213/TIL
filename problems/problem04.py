#     실수형 자료가 되었다. 
# 3. [홀수일 때 무엇을 하는가]
#     n = n * 3 + 1을 선언하고 steps_cnt변수를 1증가시킨다.
#    [왜]
#     조건문이 적용되었으니 횟수를 하나 늘려야 하고 연산자를 적용한다. 
#     while문으로 갱신된 n이 자동적으로 위로 돌아가니 추가 조건은 쓰지 않아도 된다.
# 4. [횟수를 1 늘리는 줄은 어디에 두어야 하는가]
#    (**if 안** / **else 안** / if-else 밖)
#    [왜]
#     조건문이 적용될 때마다 횟수를 늘린다는 요구사항에 따라 매 조건문 안쪽마다
#     두어야 갱신된 n이 조건을 만족할 때마다 작동할 수 있다. 
#     if조건을 만족하지 못할 시 그 안쪽의 줄은 작동하지 않으니 중복 적용될 이유가 없다. 

def count_steps_to_one(n):
    steps_cnt = 0
    while n != 1:
        if n % 2 == 0:
            n = n / 2
            # print(type(n))
            steps_cnt += 1
        else:
            n = n * 3 + 1
            steps_cnt += 1
    return steps_cnt

