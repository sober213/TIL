#     2로 나눈 나머지가 0이면 짝수, 아니면 홀수로 하는 조건문을 설정한다. 
#    [왜]
#     짝수는 2로 나눴을 때 나누어떨어지는 정수를 말한다. 나머지가 0이 되니 
#     해당 조건을 만족하면 짝수, 아니면 홀수로 본다. 
# 2. [짝수일 때 무엇을 하는가]
#     n = n // 2 를 선언하고 steps_cnt변수를 1증가시킨다.
#    [왜](확인함)
#     n // 2는 정수값 몫을 돌려주니 n의 정수 타입이 유지되게끔 나눗셈 대신 사용한다.
