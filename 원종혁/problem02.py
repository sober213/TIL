# 2. [반복 한 번마다 무엇을 하는가]
#     자리 목록의 인덱스와 낙타가 한 번에 갈 수 있는 구간 내 뒤에서부터 꺼내며 비교한다.
#    [왜]
#     한 번에 갈 수 있는 구간에서 퍼지기 싫으면 한 번은 들러야 한다. 되도록 뒤에서
#     오아시스를  들르는 편이 가장 적게 물을 채울 수 있기에 뒤에서부터 꺼낸다.
#     0번 다음에 1에서 채울 경우 1, 3, 5, 7, 9자리에 들르고
#     3에서 채울 경우 3, 5, 7에 들른다. 결과는 각각 5, 3.
# 3. [갈 수 있는 오아시스가 없을 때 무엇을 하는가]
#     즉시 함수를 종료하며 0을 반환한다.
#    [왜]
#     낙타가 퍼졌다. 현재 선 위치가 변하지 않기에(함수01이 현 낙타 위치 변경 조건을 만족하지
#     못해 마지막 위치만 반환) 종료 조건을 두지 않으면 낙타가 선 위치가 계속 출력되며 
#     루프에서 강제로 탈출해야 한다. 
# 4. [횟수를 1 늘리는 줄은 어디에 두는가]
#     반복문 내에 조건을 만족한 바로 아래 둔다.
#    [왜]
#     오아시스에 들렀을 때만 물을 채우기 때문

def count_min_refills(oases, K, N):
    refills = 0
    camel_now = 0
    oas = [0] * (N + 1)
    
    for i in range(len(oases)):
        oas[oases[i]] += 1
    
    while camel_now + K < N:
        for i in range(camel_now + K, camel_now, -1):
            if oas[i] == 1:
                refills += 1
                camel_now = i
                # print(camel_now)
                break
        if oas[i] == 0:
            return 0
    return refills

                  
         
