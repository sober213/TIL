def count_min_cha(a, b, c, c_list):
        # K N M
        # 자리 목록을 설정한다
    sta = [0] * (b + 1)
        
    for i in range(c):
        sta[c_list[i]] += 1
        # 변수를 반복문 밖에서 설정한다
    min_cha = 0
    bus_now = 0
    while bus_now + a < b:
        for i in range(bus_now + a, bus_now, -1):
            if sta[i] == 1:
                min_cha += 1
                bus_now = i
                # print(bus_now)
                break
        # bus가 정지하려면?
        if sta[i] == 0:
            return 0
    return min_cha
