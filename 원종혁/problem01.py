#       처음 작성한 코드는 break를 쓰지 않아 코드를 임의로 변경한 뒤
#       확인해보니 1이 나왔다. 조건을 만족한 즉시 반복문이 종료되어야
#       가장 큰 값이 나오는데 종료되지 않으면 마지막까지 반복문이 돌며
#       첫 오아시스까지 가게 된다.  

def find_farthest_oasis(oases, N, start, limit):
    oas = [0] * (N + 1)
    for o in range(len(oases)):
        oas[oases[o]] += 1
    farthest_oas = 0
    for i in range(limit, start, -1):
        if oas[i] == 1:
            farthest_oas = i
            break
