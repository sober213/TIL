# 2-3. [반복문 안에서 무엇을 검사하는가]
#       인덱스를 미리 만든 자리 목록에 대입해 1인지 검사
#      [왜]
#       동일 인덱스 내에서 자리 상 오아시스가 있는 값이 1이다.
